const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require(process.argv[2] || 'typescript');
const file = 'entry/src/main/ets/app/PinmonyPublishNativeFlow.ets';
const source = fs.readFileSync(file, 'utf8');
const sf = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
const flow = sf.statements.find(n => ts.isClassDeclaration(n) && n.name.text === 'PinmonyPublishNativeFlow');
const methods = ['mapDraft', 'action'].map(name => flow.members.find(n => ts.isMethodDeclaration(n) && n.name?.getText(sf) === name).getText(sf));
const scope = { exports: {} };
vm.runInNewContext(ts.transpileModule(`export class Test {${methods.join('\n')}}`, { compilerOptions: { target: ts.ScriptTarget.ES2021, module: ts.ModuleKind.CommonJS } }).outputText, scope);
const host = new scope.exports.Test();
Object.assign(host, { web: value => typeof value === 'string' && /^https:\/\//.test(value) ? value : '', current: () => true, viewer: 'synthetic-viewer', commit() {} });
// Field names follow the captured draft response; all values here are synthetic.
const product = { pin_id: '123', product_id: '456', status: 'created', media: { url: 'https://example.test/product.jpg', width: 200, height: 300 }, link: 'https://example.test/item' };
const draft = host.mapDraft({ id: '789', pages: [{ blocks: [{ block_type: 2, image: { images: { '750x': { url: 'https://example.test/draft.jpg', width: 750, height: 1000 } } } }] }], draft: { tagged_products: [product, product, { ...product, pin_id: 'invalid' }, { ...product, pin_id: '124', status: 'pending' }, { ...product, pin_id: '125', media: {} }] } });
assert.equal(draft.products.length, 1);
assert.equal(draft.products[0].id, '123', 'use Pin identity rather than product identity');
assert.equal(draft.products[0].imageUrl, product.media.url);
assert.equal(draft.products[0].imageHeight, 300);
assert.equal(draft.products[0].targetUrl, product.link);
(async () => {
  host.flow = { kind: 'photo', phase: 'productSearch', productSuggestions: ['old suggestion'], productResults: [{}], productLoading: true, selectedProducts: draft.products };
  host.productSequence = 5;
  await host.action('productQuery', '', false);
  assert.equal(host.productSequence, 6, 'invalidate pending suggestions');
  assert.equal(host.flow.productSuggestions.length, 0);
  assert.equal(host.flow.productResults.length, 0);
  assert.equal(host.flow.productLoading, false);
  assert.equal(host.flow.productSuggesting, true);
  assert.equal(host.flow.selectedProducts.length, 1, 'clearing search preserves selected products');
  host.flow.phase = 'select';
  await host.action('products', '', false);
  assert.equal(host.flow.phase, 'productConfirm');
  await host.action('addProduct', '', false);
  assert.equal(host.flow.phase, 'products');
  host.flow.phase = 'productConfirm';
  await host.action('doneProducts', '', false);
  assert.equal(host.flow.phase, 'select');
  const pageFile = 'feature_profile/src/main/ets/components/PinmonyPublishPage.ets';
  const pageSource = fs.readFileSync(pageFile, 'utf8').replace('export struct PinmonyPublishPage', 'export class PinmonyPublishPage');
  const pageTree = ts.createSourceFile(pageFile, pageSource, ts.ScriptTarget.Latest, true);
  const page = pageTree.statements.find(n => ts.isClassDeclaration(n) && n.name?.text === 'PinmonyPublishPage');
  const confirm = page.members.find(n => ts.isMethodDeclaration(n) && n.name?.getText(pageTree) === 'confirmDeleteDraft');
  vm.runInNewContext(ts.transpileModule(`export class Page {${confirm.getText(pageTree)}}`, { compilerOptions: { target: ts.ScriptTarget.ES2021, module: ts.ModuleKind.CommonJS } }).outputText, scope);
  const view = new scope.exports.Page();
  let dialog, deletes = 0;
  Object.assign(view, { state: { token: 1, phase: 'photo', drafts: [{ id: '789' }] }, uiText: key => key, getUIContext: () => ({ showAlertDialog: options => { dialog = options; } }), onAction: () => { deletes++; } });
  view.confirmDeleteDraft('789');
  assert.equal(deletes, 0, 'opening confirmation cannot delete');
  dialog.secondaryButton.action();
  assert.equal(deletes, 0, 'cancel cannot delete');
  dialog.primaryButton.action();
  assert.equal(deletes, 1);
  view.state.token = 2;
  dialog.primaryButton.action();
  assert.equal(deletes, 1, 'stale confirmation cannot delete from a new flow');
  console.log('Draft products: captured schema normalization, identity, invalid records, deduplication and search clear passed');
  console.log('Publish flow: existing-product entry, add, done and draft confirmation/cancel/stale token passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
