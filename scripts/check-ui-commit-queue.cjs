const assert = require('node:assert/strict');
const ts = require(process.argv[2] || 'typescript');
const { Queue, flush, timers } = require('./ui-commit-harness.cjs').createUiCommitHarness(ts);
const queue = new Queue(), calls = [];
queue.post('refresh', () => calls.push('old'));
queue.post('refresh', () => calls.push('latest'));
queue.post('photo', () => calls.push('photo'));
assert.deepEqual(calls, [], 'callbacks never run inside render callback');
assert.equal(timers.size, 1, 'coalesce a render batch into one cancellable timer');
flush(); assert.deepEqual(calls, ['latest', 'photo']);
queue.post('cancel', () => calls.push('disposed')); queue.dispose(); flush();
queue.post('late', () => calls.push('late')); flush();
assert.deepEqual(calls, ['latest', 'photo']);
queue.activate(); queue.post('new', () => calls.push('new')); flush();
assert.deepEqual(calls, ['latest', 'photo', 'new']);
queue.post('replace', () => { queue.clear(); queue.post('replacement', () => calls.push('replacement')); });
queue.post('stale', () => calls.push('stale-batch')); flush();
assert.deepEqual(calls, ['latest', 'photo', 'new', 'replacement'], 'clearing during commit invalidates rest of old batch');
queue.post('teardown', () => queue.dispose()); queue.post('after', () => calls.push('after-teardown')); flush();
assert(!calls.includes('after-teardown'));
console.log('UI commit queue: deferred writes, coalescing, disposal, remount, cancellation and reentrant invalidation passed');
