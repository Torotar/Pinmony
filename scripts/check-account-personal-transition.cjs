const fs=require('node:fs'),assert=require('node:assert/strict');
const page=fs.readFileSync('feature_settings/src/main/ets/components/PinmonySettingsPage.ets','utf8');
const account=fs.readFileSync('feature_settings/src/main/ets/components/PinmonyAccountPage.ets','utf8');
const method=page.slice(page.indexOf('private settingsPageScreens()'),page.indexOf('\n  build()',page.indexOf('private settingsPageScreens()')));
assert(method.includes('private settingsPageScreens()'), 'route helper exists');
assert(page.includes('ForEach(this.settingsPageScreens(), (_screen:'), 'render the verified route keys');
const keys=new Function(method.slice(method.indexOf('{')+1,method.lastIndexOf('}')));
assert.deepEqual(keys.call({store:{screen:'account'}}),['account']);
assert.deepEqual(keys.call({store:{screen:'personal'}}),['account','personal'],'parent key survives; only new personal layer enters');
assert.deepEqual(keys.call({store:{screen:'root'}}),[]);
assert.deepEqual(keys.call({store:{screen:'gender'}}),['gender']);
assert.deepEqual(keys.call({store:{screen:'socialMessages'}}),['social','socialMessages']);
assert(page.includes("retainedAccount: screen === 'account' && this.store.screen === 'personal'"));
assert(page.includes(".hitTestBehavior(_screen !== this.store.screen ? HitTestMode.None : HitTestMode.Default)"));
assert(page.includes(".accessibilityLevel(_screen !== this.store.screen ? 'no-hide-descendants' : 'auto')"));
assert.equal((account.match(/this\.retainedAccount \|\| this\.store\.screen === 'account'/g)||[]).length,4,'retained parent keeps its own title, loading body, content and email status');
assert(page.includes("TransitionEffect.translate({x:'100%'}).animation({duration:180,curve:Curve.EaseOut})"));
console.log('Account to personal: stable parent key/title/body, incoming animation and underlying interaction isolation passed');
