const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require(process.argv[2] || 'typescript');
const { createArktsLoader } = require('./arkts-module-loader.cjs');
const { PinmonyProfileStore: Store } = createArktsLoader(ts).loadFile('feature_profile/src/main/ets/stores/PinmonyProfileStore.ets');
const root = fs.readFileSync('entry/src/main/ets/components/PinmonyProfileRootContent.ets', 'utf8');
const start = root.indexOf('onScrollPosition: ');
const end = root.indexOf('\n                  loading:', start);
assert(start >= 0 && end > start);
const callback = root.slice(start + 'onScrollPosition: '.length, end).trim().replace(/,$/, '');
const store = new Store();
let setterCalls = 0;
const descriptor = Object.getOwnPropertyDescriptor(Store.prototype, 'profileScrollOffset');
Object.defineProperty(store, 'profileScrollOffset', { get() { return descriptor.get.call(this); }, set(value) { setterCalls++; descriptor.set.call(this, value); } });
store.profile = { profileUrl: 'synthetic-profile', section: 'created' };
store.profileNativeReadsReady = true;
let cachedOffset;
store.profileCache.put = (_, offset) => { cachedOffset = offset; };
const view = { coveredByBoard: false, coveredByPin: false, profileStore: store, currentProfileUrl: () => 'synthetic-profile' };
const report = vm.runInNewContext(ts.transpileModule('const callback = ' + callback + '; callback;', { compilerOptions: { target: ts.ScriptTarget.ES2021 } }).outputText, { view });
for (let i = 0; i < 600; i++) report('synthetic-profile', 'created', i + 0.25);
assert.equal(store.profileScrollOffset, 599.25);
assert.equal(cachedOffset, 599.25);
assert.equal(setterCalls, 0, 'continuous bookkeeping bypasses the observed public setter');
for (const field of ['coveredByBoard', 'coveredByPin']) {
  view[field] = true; report('synthetic-profile', 'created', 900); view[field] = false;
  assert.equal(store.profileScrollOffset, 599.25);
}
report('stale-profile', 'created', 900);
report('synthetic-profile', 'saved', 900);
view.currentProfileUrl = () => 'other-profile'; report('synthetic-profile', 'created', 900);
assert.equal(store.profileScrollOffset, 599.25, 'late callbacks cannot change another route');
store.profileScrollOffset = 42.5; assert.equal(store.profileScrollOffset, 42.5);
store.profileScrollOffset = 0; assert.equal(store.profileScrollOffset, 0);
assert.equal(new Store().profileScrollOffset, 0, 'stores do not share return position');
const page = fs.readFileSync('feature_profile/src/main/ets/components/PinmonyProfilePage.ets', 'utf8');
const card = page.slice(page.indexOf('private createdPinCard('), page.indexOf('private createdPinCard(') + 1800);
assert.match(card, /Image\(pin.imageUrl\)/, 'profile thumbnails retain the original direct native Image path');
assert(!card.includes('PinmonyCdnImage'), 'profile thumbnails do not enter the added shared download/decode queue');
assert(!card.includes('viewportOnly') && !card.includes('loadingActive'), 'original native image loading is not delayed by added admission gates');
assert.match(card, /\.height\(this.pinHeight\(pin\)\)/);
assert.match(card, /\.objectFit\(ImageFit.Cover\)\s*\.borderRadius\(16\)/, 'original native image crop and rounded corners are retained');
assert.match(card, /\.id\('pinmony-profile-photo-' \+ pin.id\)/);
console.log('Profile downward scroll: exact retention, route guards, reset and original native thumbnail loading/rounding passed (source logic, not device frame timing)');
