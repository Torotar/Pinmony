const Host = context.exports.PinmonyBackToTopButton;
const h = new Host(); h.showButton = true; h.hostWidth = 400; h.hostHeight = 800; h.scrollOffsetVp = 1600; h.aboutToAppear();
let clicks=0; h.onBackToTop=()=>clicks++;
let stopped=0;
const touch=(type,x=100,y=100,id=1)=>h.touch({type,touches:[{windowX:x,windowY:y,id}],stopPropagation(){stopped++;}});
touch(0); assert(h.tracking); touch(1); assert(!h.tracking); h.click(); assert.equal(clicks,1);
touch(0); touch(3,140,80); assert(h.pulled); assert(h.tracking); h.click(); assert.equal(clicks,1);
touch(1); assert.equal(h.pullX,undefined); assert.equal(h.pullY,undefined); assert(!h.tracking); h.click(); assert.equal(clicks,1); now+=401; h.click(); assert.equal(clicks,2);
touch(0); touch(3,-10000,10000); assert(h.pulled); touch(2); assert.equal(h.pullX,undefined); h.click(); assert.equal(clicks,2);
now+=401; touch(0); touch(3,130,100,2); assert.equal(h.pullX,undefined); h.touch({type:3,touches:[{},{}],stopPropagation(){stopped++;}}); assert(!h.tracking);
touch(0); touch(3,NaN,100); assert.equal(h.pullX,undefined); touch(3,120,100); h.showButton=false; h.availabilityChanged(); assert(!h.tracking); assert.equal(h.pullX,undefined); now+=500; h.click(); assert.equal(clicks,2);
h.showButton=true; touch(0); touch(3,120,110); h.aboutToDisappear(); assert.equal(h.pullX,undefined); assert.equal(h.pullY,undefined); now+=500; touch(0); h.click(); assert.equal(clicks,2);
