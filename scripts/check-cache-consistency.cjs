const assert = require('node:assert/strict');
const fs = require('node:fs');

const disk = fs.readFileSync('common_foundation/src/main/ets/cache/DiskCache.ets', 'utf8');
const api = fs.readFileSync('common_foundation/src/main/ets/cache/ApiCache.ets', 'utf8');
