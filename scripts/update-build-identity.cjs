const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const root = path.resolve(__dirname, '..'), target = path.join(root, 'entry/src/main/ets/app/PinmonyBuildIdentity.ets');
function files(dir) { return fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => e.isDirectory() ? (e.name === 'src' ? walk(path.join(dir, e.name)) : []) : []); }
function walk(dir) { return fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(dir, e.name)) : (e.name.endsWith('.ets') || dir.split(path.sep).includes('resources') || e.name === 'module.json5') ? [path.join(dir, e.name)] : []); }
const paths = fs.readdirSync(root).filter(n => n === 'entry' || n.startsWith('feature_') || n.startsWith('common_')).flatMap(n => files(path.join(root, n))).filter(p => p !== target).sort();
for (const moduleName of fs.readdirSync(root).filter(n => n === 'entry' || n.startsWith('feature_') || n.startsWith('common_'))) {
  for (const name of ['oh-package.json5', 'hvigorfile.ts']) {
    const candidate = path.join(root, moduleName, name);
    if (fs.existsSync(candidate)) paths.push(candidate);
  }
}
paths.push(...walk(path.join(root, 'AppScope')).filter(p => p !== path.join(root, 'AppScope/app.json5')));
for (const name of ['oh-package.json5', 'oh-package-lock.json5', 'hvigorfile.ts', 'scripts/update-build-identity.cjs']) {
  const candidate = path.join(root, name);
  if (fs.existsSync(candidate)) paths.push(candidate);
}
paths.sort();
const config = fs.readFileSync(path.join(root, 'AppScope/app.json5'), 'utf8'), hash = crypto.createHash('sha256').update(config);
for (const p of paths)
    hash.update(path.relative(root, p).replaceAll('\\', '/')).update(fs.readFileSync(p));
const value = key => config.match(new RegExp('"' + key + '"\\s*:\\s*("[^"\\n]+"|[0-9]+)'))?.[1];
const revision = hash.digest('hex').slice(0, 12), version = value('versionName'), code = value('versionCode'), build = value('buildVersion');
if (!version || !code || !build)
    throw Error('Missing app build identity');
const content = '// Deterministic local source identity; generated by scripts/update-build-identity.cjs.\nexport const PINMONY_BUILD_IDENTITY: string = ' + JSON.stringify('version=' + JSON.parse(version) + ' versionCode=' + code + ' build=' + build + ' revision=local-' + revision) + ';\n';
if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== content)
        throw Error('Build identity is stale');
}
else if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content)
    fs.writeFileSync(target, content);
console.log('Build identity: local-' + revision);
