const assert = require('node:assert/strict');
const ts = require(process.argv[2] || 'typescript');
const Store = require('./arkts-module-loader.cjs').createArktsLoader(ts).loadFile('feature_inbox/src/main/ets/stores/PinmonyInboxStore.ets').PinmonyInboxStore;
const store = new Store();
store.inbox = {section: 'messages', items: [{id: 'conversation:100', unread: true, unreadCount: 3}, {id: 'conversation:200', unread: true, unreadCount: 2}]};
store.inboxMessagesUnreadCount = 5;
let propagated = -1;
store.onUnreadChange = (_u, _m, _uc, mc) => { propagated = mc; };
const stamp = '2026-11-08T01:00:00Z';
store.acknowledgeConversation('100', stamp);
assert.equal(store.inbox.items[0].unreadCount, 0);
assert.equal(store.inbox.items[1].unreadCount, 2);
assert.equal(propagated, 2, 'entry updates bottom count without return/refresh');
store.acknowledgeConversation('100', stamp);
assert.equal(store.inboxMessagesUnreadCount, 2, 'repeat entry cannot subtract another conversation');
for (const old of [stamp, '', '2026-11-08T00:00:00Z']) assert.equal(store.isUnseenConversation('100', old), false);
store.acknowledgeConversation('100', '2026-11-08T00:00:00Z');
assert.equal(store.isUnseenConversation('100', stamp), false, 'late older chat response cannot regress acknowledgement');
assert.equal(store.isUnseenConversation('100', '2026-11-08T02:00:00Z'), true);
assert.equal(store.isUnseenConversation('200', stamp), true);
store.clearViewedConversations();
assert.equal(store.isUnseenConversation('100', stamp), true, 'account reset clears receipts');
console.log('Chat entry unread: immediate row/bottom propagation, other chats, repeat entry, stale responses, new messages and reset passed');
