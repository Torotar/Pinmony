const assert=require('node:assert/strict'),fs=require('node:fs');
const ts=require(process.argv[2]||'typescript');
const {createHomeRuntime}=require('./home-controller-harness.cjs');
let serial=0;const timers=new Map();
const runtime=createHomeRuntime(ts,{setTimeout:(fn,delay)=>{const id=++serial;timers.set(id,{fn,delay});return id;},clearTimeout:id=>timers.delete(id)});
const root='https://www.pinterest.com/';
const pin=(id,title='')=>({id,pinUrl:root+'pin/'+id+'/',imageUrl:'https://i.pinimg.com/'+id+'.jpg',imageWidth:200,imageHeight:300,title,hasMore:false});
const all={id:'all',label:'所有',selected:true,enabled:true}, board={id:'board',label:'Board',selected:false,enabled:true};
const snapshot=(session,pins,changes={})=>({kind:'state',session,pageKey:root,selectedTab:'所有',tabs:[all,board],pins,dataSource:'api',...changes});
const flush=()=>new Promise(resolve=>setImmediate(resolve));
async function main(){
 const h=runtime.harness();
 const saved=snapshot(9,[pin('123','API title'),pin('456')]);h.store.cachedHome=saved;h.store.cachedHomeScrollOffset=400;
 h.controller.prepareHomeForPageBegin(root);assert.equal(h.store.home,saved);assert.equal(h.store.homeActionsReady,false);
 h.controller.updateHome(JSON.stringify(snapshot(1,[pin('789')])));
 assert.deepEqual(Array.from(h.store.home.pins,p=>p.id),['123','456']);assert.equal(h.store.home.session,1);assert.equal(h.store.cachedHomeScrollOffset,400);
 h.controller.updateHomePinTitle(root+'pin/123/','detail title');
 assert.equal(h.store.home.pins[0].title,'API title','API card titles remain owned by the homepage API');
 h.controller.updateHome(JSON.stringify({kind:'title',session:1,pageKey:root,pinUrl:root+'pin/123/',title:'legacy DOM title'}));
 assert.equal(h.store.home.pins[0].title,'API title','unsupported legacy title messages do not alter API content');
 await h.controller.loadMoreHome();h.controller.updateHome(JSON.stringify(snapshot(2,[pin('789')])));
 assert.deepEqual(Array.from(h.store.home.pins,p=>p.id),['123','456','789']);
 h.controller.refreshHome();h.controller.updateHome(JSON.stringify(snapshot(3,[pin('999')],{refreshing:true})));
 assert.equal(h.store.home.pins[0].id,'123','refresh loading keeps the returned feed');
 h.controller.updateHome(JSON.stringify(snapshot(3,[pin('999')])));
 assert.deepEqual(Array.from(h.store.home.pins,p=>p.id),['999'],'confirmed refresh replaces it');
 h.controller.invalidatePending();
 const category=runtime.harness();category.store.cachedHome=saved;
 category.controller.prepareHomeForPageBegin(root);
 category.controller.updateHome(JSON.stringify(snapshot(1,[pin('789')],{selectedTab:'Board',tabs:[{...all,selected:false},{...board,selected:true}]})));
 assert.equal(category.store.home.selectedTab,'所有');
 const redispatch=[...timers].find(([,timer])=>timer.delay===0);assert(redispatch,'return schedules restoration of the retained category');
 timers.delete(redispatch[0]);redispatch[1].fn();await flush();
 assert(category.events.some(e=>e[0]==='js'&&e[1].includes('PinmonyHomeTab(1,')&&e[1].includes('"all"')));
 category.controller.invalidatePending();
 const failing=runtime.harness();failing.store.cachedHome=saved;failing.controller.prepareHomeForPageBegin(root);
 const expected=failing.store.home;failing.controller.updateHome(JSON.stringify(snapshot(1,[],{kind:'failed',error:'real failure'})));
 assert.equal(failing.store.home,expected);assert.equal(failing.store.homeError,'real failure');assert.equal(failing.store.homeActionsReady,false);
 failing.controller.prepareHomeForPageBegin(root,true);assert.equal(failing.store.home,expected);
 failing.controller.prepareHomeForPageBegin(root+'search/');assert.equal(failing.store.home,expected,'another root document preserves home presentation');
 failing.controller.prepareHomeForPageBegin(root+'pin/123/');assert.equal(failing.store.home,undefined);
 assert.equal(failing.store.cachedHome,expected,'child navigation keeps the completed return source');
 failing.controller.invalidatePending();
 const source=fs.readFileSync('feature_home/src/main/ets/services/PinmonyHomeScript.ets','utf8');
 assert.doesNotMatch(source,/querySelector|querySelectorAll|MutationObserver|PinmonyHomeTitles/);
 console.log('Home retention: actual controller/Store, API title ownership, category restoration, pagination, refresh replacement, failure retention and route isolation passed');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
